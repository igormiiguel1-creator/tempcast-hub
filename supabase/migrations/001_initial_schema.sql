  duration          TEXT,
  platform_status   TEXT,
  overview          TEXT,
  notes             TEXT,
  sponsors          TEXT[] NOT NULL DEFAULT '{}',
  checklist         JSONB NOT NULL DEFAULT '[]',
  files             JSONB NOT NULL DEFAULT '[]',
  timeline          JSONB NOT NULL DEFAULT '[]',
  recent_activity   JSONB NOT NULL DEFAULT '[]',
